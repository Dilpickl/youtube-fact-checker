const track = (overrides: Partial<CaptionTrack>): CaptionTrack => ({
  url: "https://v16-webapp.tiktok.com/captions/x.vtt",
  language: "",
  format: "webvtt",
  autoGenerated: true,
  original: false,
  ...overrides,
});

test("reads the video from a video page's embedded data", () => {
  assert.deepEqual(extractVideos(embeddedPage), [
    {
      id: "7621991999251467550",
      author: "example_creator",
      description: "she ws so sweet #ubereats #fyp",
      hashtags: ["ubereats", "fyp"],
      onScreenText: ["sneaking taco bell into school"],
      captionTracks: [],
      noCaptionReason: 3,
      aiLabel: { labeled: false, description: "" },
    },
  ]);
});

test("reads every video in a feed response and skips entries that aren't videos", () => {
  const ids = extractVideos(feedResponse).map((video) => video.id);
  assert.deepEqual(ids, ["7600000000000000001", "7600000000000000002"]);
});

test("merges a caption track TikTok lists in both places", () => {
  const [video] = extractVideos(feedResponse);
  assert.deepEqual(video.captionTracks, [
    {
      url: "https://v16-webapp.tiktok.com/captions/en.vtt",
      language: "eng-US",
      format: "webvtt",
      autoGenerated: true,
      original: true,
    },
    {
      url: "https://v16-webapp.tiktok.com/captions/es.vtt",
      language: "spa-ES",
      format: "webvtt",
      autoGenerated: false,
      original: false,
    },
  ]);
});

test("reports TikTok's AI label", () => {
  const [unlabeled, labeled] = extractVideos(feedResponse);
  assert.deepEqual(unlabeled.aiLabel, { labeled: false, description: "" });
  assert.deepEqual(labeled.aiLabel, {
    labeled: true,
    description: "Creator labeled as AI-generated",
  });
  const flagOnly = { itemList: [{ id: "1", IsAigc: true, video: {} }] };
  assert.equal(extractVideos(flagOnly)[0].aiLabel.labeled, true);
});

// Regression: the first videos on the For You page were never reported because
// TikTok embeds them under "webapp.updated-items", seen on 2026-10-13.
test("reads the videos embedded in the For You page", () => {
  const forYouPage = {
    __DEFAULT_SCOPE__: {
      "webapp.updated-items": [
        { id: "7681077416399326495", video: {} },
        { id: "7675538187468541216", video: {} },
      ],
    },
  };
  assert.deepEqual(
    extractVideos(forYouPage).map((video) => video.id),
    ["7681077416399326495", "7675538187468541216"],
  );
});

// Regression: a creator-labeled video printed "no" because only IsAigc and
// AIGCDescription were checked. Field values copied from the live video.
test("reports the creator's AI label when only aigcLabelType is set", () => {
  const creatorLabeled = {
    itemList: [
      {
        id: "7693460283968245013",
        IsAigc: false,
        AIGCDescription: "",
        ShowAIGC: true,
        aigcLabelType: "1",
        video: {},
      },
    ],
  };
  assert.equal(extractVideos(creatorLabeled)[0].aiLabel.labeled, true);
});

test("returns nothing for responses that aren't video data", () => {
  for (const json of [null, "text", 42, [], {}, { itemList: "nope" }]) {
    assert.deepEqual(extractVideos(json), []);
  }
});

test("picks captions in the speaker's language, then English, then any", () => {
  const spanishTranslation = track({ language: "spa-ES" });
  const englishOriginal = track({ language: "eng-US", original: true });
  const french = track({ language: "fra-FR" });
  const english = track({ language: "en" });
  assert.equal(
    pickCaptionTrack([spanishTranslation, englishOriginal]),
    englishOriginal,
  );
  assert.equal(pickCaptionTrack([french, english]), english);
  assert.equal(pickCaptionTrack([french]), french);
  assert.equal(pickCaptionTrack([track({ format: "srt" })]), null);
  assert.equal(pickCaptionTrack([]), null);
});

test("finds the video id from the player's wrapper, then the address", () => {
  const feedPlayer = ["", "xgwrapper-0-7621991999251467550", "media-card-0"];
  assert.equal(videoIdFrom(feedPlayer, "/foryou"), "7621991999251467550");
  assert.equal(
    videoIdFrom(["media-card-0"], "/@someone/video/7600000000000000001"),
    "7600000000000000001",
  );
  assert.equal(
    videoIdFrom(feedPlayer, "/@someone/video/7600000000000000001"),
    "7621991999251467550",
  );
  assert.equal(videoIdFrom(["app"], "/foryou"), null);
});

test("only treats TikTok's own servers as caption sources", () => {
  assert.ok(isTikTokCaptionUrl("https://v16-webapp-prime.us.tiktok.com/a.vtt"));
  assert.ok(isTikTokCaptionUrl("https://p16-sign.tiktokcdn-us.com/a.vtt"));
  assert.ok(isTikTokCaptionUrl("https://v19.tiktokcdn.com/a.vtt"));
  assert.ok(!isTikTokCaptionUrl("http://v16-webapp.tiktok.com/a.vtt"));
  assert.ok(!isTikTokCaptionUrl("https://tiktok.com.evil.example/a.vtt"));
  assert.ok(!isTikTokCaptionUrl("https://eviltiktok.com/a.vtt"));
  assert.ok(!isTikTokCaptionUrl("not a url"));
});

test("only reads responses from TikTok's API", () => {
  assert.ok(
    isTikTokApiUrl("https://www.tiktok.com/api/recommend/item_list/?count=6"),
  );
  assert.ok(!isTikTokApiUrl("https://www.tiktok.com/@nasa"));
  assert.ok(!isTikTokApiUrl("https://v16.tiktokcdn.com/api/item_list/"));
  assert.ok(!isTikTokApiUrl(""));
});
