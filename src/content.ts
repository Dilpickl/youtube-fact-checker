// Runs in the extension's isolated world on tiktok.com. Collects video records
// from the page, notices which video starts playing, and (for milestone 1)
// prints its transcript and AI label to the browser console.
import {
  PAGE_HOOK_SOURCE,
  type FetchCaptionRequest,
  type FetchCaptionResponse,
} from "./messages.ts";
import {
  EMBEDDED_DATA_ELEMENT_ID,
  extractVideos,
  pickCaptionTrack,
  videoIdFrom,
  type TikTokVideo,
} from "./tiktok.ts";
import { parseWebVtt } from "./webvtt.ts";

const LOG_PREFIX = "[Fact check]";
const DATA_WAIT_MS = 5000;

const videosById = new Map<string, TikTokVideo>();
const reported = new Set<string>();
let waitingForId: string | null = null;

function remember(videos: TikTokVideo[]): void {
  for (const video of videos) videosById.set(video.id, video);
  if (waitingForId && videosById.has(waitingForId)) {
    const id = waitingForId;
    waitingForId = null;
    void report(id);
  }
}

window.addEventListener("message", (event) => {
  if (
    event.source !== window ||
    event.data?.source !== PAGE_HOOK_SOURCE ||
    !Array.isArray(event.data.videos)
  ) {
    return;
  }
  remember(event.data.videos);
});

document.addEventListener("DOMContentLoaded", () => {
  const embedded = document.getElementById(EMBEDDED_DATA_ELEMENT_ID);
  if (!embedded?.textContent) return;
  try {
    remember(extractVideos(JSON.parse(embedded.textContent)));
  } catch {
    console.warn(`${LOG_PREFIX} Couldn't read TikTok's page data.`);
  }
});

// "play" doesn't bubble, so listen in the capture phase to hear every video.
document.addEventListener(
  "play",
  (event) => {
    if (!(event.target instanceof HTMLVideoElement)) return;
    const id = videoIdFrom(ancestorIds(event.target), location.pathname);
    if (!id || reported.has(id)) return;
    if (videosById.has(id)) {
      void report(id);
      return;
    }
    waitingForId = id;
    setTimeout(() => {
      if (waitingForId !== id) return;
      waitingForId = null;
      console.warn(
        `${LOG_PREFIX} Video ${id} is playing, but its TikTok data wasn't captured.`,
      );
    }, DATA_WAIT_MS);
  },
  true,
);

function ancestorIds(element: Element): string[] {
  const ids: string[] = [];
  for (let node = element.parentElement; node; node = node.parentElement) {
    if (node.id) ids.push(node.id);
  }
  return ids;
}

async function report(id: string): Promise<void> {
  const video = videosById.get(id);
  if (!video || reported.has(id)) return;
  reported.add(id);
  const transcript = await loadTranscript(video);

  const { labeled, description } = video.aiLabel;
  console.group(`${LOG_PREFIX} @${video.author} · video ${video.id}`);
  console.log(
    "TikTok AI label:",
    labeled ? `yes${description ? ` ("${description}")` : ""}` : "no",
  );
  console.log("Caption:", video.description || "(none)");
  if (video.onScreenText.length > 0) {
    console.log("On-screen text:", video.onScreenText.join(" | "));
  }
  console.log("Transcript:", transcript);
  console.groupEnd();
}

async function loadTranscript(video: TikTokVideo): Promise<string> {
  const track = pickCaptionTrack(video.captionTracks);
  if (!track) {
    return video.noCaptionReason === null
      ? "none"
      : `none (TikTok reason code ${video.noCaptionReason})`;
  }
  const kind = `${track.autoGenerated ? "auto-generated " : ""}captions, ${track.language || "unknown language"}`;
  try {
    const cues = parseWebVtt(await fetchCaptionFile(track.url));
    return `(${kind}) ${cues.map((cue) => cue.text).join(" ") || "[empty]"}`;
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return `couldn't load ${kind}: ${reason}`;
  }
}

// Try the request the way TikTok's own player would. If the caption server
// refuses requests from the page, the background script fetches it instead.
async function fetchCaptionFile(url: string): Promise<string> {
  try {
    const response = await fetch(url);
    if (response.ok) return await response.text();
  } catch {
    // Blocked by the caption server's cross-origin rules; fall through.
  }
  const request: FetchCaptionRequest = { type: "fetchCaption", url };
  const response: FetchCaptionResponse | undefined =
    await chrome.runtime.sendMessage(request);
  if (!response) throw new Error("the background script didn't answer");
  if (!response.ok) throw new Error(response.error);
  return response.text;
}
