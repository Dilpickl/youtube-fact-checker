// Everything that depends on how TikTok's website is built lives in this file,
// so when TikTok changes its site there is one place to fix. Structure observed
// on tiktok.com on 2026-10-12.

export interface CaptionTrack {
  url: string;
  language: string;
  format: string;
  autoGenerated: boolean;
  original: boolean;
}

export interface TikTokVideo {
  id: string;
  author: string;
  description: string;
  hashtags: string[];
  onScreenText: string[];
  captionTracks: CaptionTrack[];
  noCaptionReason: number | null;
  aiLabel: { labeled: boolean; description: string };
}

/** The script element where TikTok embeds each page's initial data. */
export const EMBEDDED_DATA_ELEMENT_ID = "__UNIVERSAL_DATA_FOR_REHYDRATION__";

// Keep in sync with host_permissions in extension/manifest.json.
const CAPTION_DOMAINS = ["tiktok.com", "tiktokcdn.com", "tiktokcdn-us.com"];

type Json = Record<string, unknown>;

const asObject = (value: unknown): Json | undefined =>
  typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Json)
    : undefined;
const asArray = (value: unknown): unknown[] =>
  Array.isArray(value) ? value : [];
const asString = (value: unknown): string =>
  typeof value === "string" ? value : "";

/** Pulls every video record out of a TikTok API response or embedded page data. */
export function extractVideos(json: unknown): TikTokVideo[] {
  const root = asObject(json);
  if (!root) return [];
  const pageScope = asObject(root.__DEFAULT_SCOPE__);
  const candidates = pageScope
    ? [
        asObject(asObject(pageScope["webapp.video-detail"])?.itemInfo)
          ?.itemStruct,
      ]
    : [...asArray(root.itemList), asObject(root.itemInfo)?.itemStruct];
  return candidates.flatMap((candidate) => {
    const video = toVideo(candidate);
    return video ? [video] : [];
  });
}

function toVideo(value: unknown): TikTokVideo | null {
  const item = asObject(value);
  const video = asObject(item?.video);
  const id = asString(item?.id);
  if (!item || !video || !/^\d+$/.test(id)) return null;

  const captionInfo = asObject(video.claInfo);
  const tracks = [
    ...asArray(captionInfo?.captionInfos),
    ...asArray(video.subtitleInfos),
  ].flatMap((entry) => {
    const track = toCaptionTrack(entry);
    return track ? [track] : [];
  });
  const reason = captionInfo?.noCaptionReason;
  const aiDescription = asString(item.AIGCDescription);

  return {
    id,
    author: asString(asObject(item.author)?.uniqueId),
    description: asString(item.desc),
    hashtags: asArray(item.textExtra)
      .map((tag) => asString(asObject(tag)?.hashtagName))
      .filter(Boolean),
    onScreenText: asArray(item.stickersOnItem)
      .flatMap((sticker) =>
        asArray(asObject(sticker)?.stickerText).map(asString),
      )
      .filter(Boolean),
    captionTracks: tracks.filter(
      (track, index) =>
        tracks.findIndex((other) => other.url === track.url) === index,
    ),
    noCaptionReason: typeof reason === "number" ? reason : null,
    aiLabel: {
      labeled: item.IsAigc === true || aiDescription !== "",
      description: aiDescription,
    },
  };
}

// TikTok lists captions in two places with different field names:
// video.claInfo.captionInfos (camelCase) and video.subtitleInfos (PascalCase).
// The entry field names come from TikTok pages seen before 2026; only empty
// caption lists could be inspected on 2026-10-12, so confirm them on a live video.
function toCaptionTrack(value: unknown): CaptionTrack | null {
  const entry = asObject(value);
  if (!entry) return null;
  const url =
    asString(entry.url) ||
    asString(entry.Url) ||
    asString(asArray(entry.urlList)[0]) ||
    asString(asArray(entry.UrlList)[0]);
  if (!url) return null;
  return {
    url,
    language: asString(entry.language) || asString(entry.LanguageCodeName),
    format: (
      asString(entry.captionFormat) || asString(entry.Format)
    ).toLowerCase(),
    autoGenerated: entry.isAutoGen === true || entry.Source === "ASR",
    original: entry.isOriginalCaption === true || entry.Source === "ASR",
  };
}

/** Prefers captions in the speaker's own language, then English, then any. */
export function pickCaptionTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  const readable = tracks.filter(
    (track) => track.format === "" || track.format === "webvtt",
  );
  return (
    readable.find((track) => track.original) ??
    readable.find((track) => /^en/i.test(track.language)) ??
    readable[0] ??
    null
  );
}

/**
 * Finds which TikTok video a player belongs to. TikTok wraps each player in an
 * element whose id ends with the video's id (`xgwrapper-0-7621991999251467550`);
 * on a single video's page the id is also in the address (`/@user/video/7621…`).
 */
export function videoIdFrom(
  ancestorIds: string[],
  pathname: string,
): string | null {
  for (const id of ancestorIds) {
    const match = /^xgwrapper-\d+-(\d+)$/.exec(id);
    if (match) return match[1];
  }
  return /\/video\/(\d+)/.exec(pathname)?.[1] ?? null;
}

/** Whether a network response might carry video records worth reading. */
export function isTikTokApiUrl(url: string): boolean {
  const parsed = parseHttpsUrl(url);
  return (
    parsed !== null &&
    isOnDomain(parsed.hostname, "tiktok.com") &&
    parsed.pathname.startsWith("/api/")
  );
}

/** Whether a caption file address points at TikTok's own servers. */
export function isTikTokCaptionUrl(url: string): boolean {
  const parsed = parseHttpsUrl(url);
  return (
    parsed !== null &&
    CAPTION_DOMAINS.some((domain) => isOnDomain(parsed.hostname, domain))
  );
}

function parseHttpsUrl(url: string): URL | null {
  try {
    const parsed = new URL(url);
    return parsed.protocol === "https:" ? parsed : null;
  } catch {
    return null;
  }
}

const isOnDomain = (hostname: string, domain: string): boolean =>
  hostname === domain || hostname.endsWith(`.${domain}`);
